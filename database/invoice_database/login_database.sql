-- 🟦 1. USER ACCOUNTS
-- Stores user information, roles and approval status.

CREATE TABLE IF NOT EXISTS login_database (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Personal Details
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,

    -- Login Details
    username VARCHAR(14) NOT NULL UNIQUE,
    mobile VARCHAR(10) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,

    -- Django password hash only
    password VARCHAR(128) NOT NULL,

    -- User Role and Permissions
    role VARCHAR(20) NOT NULL DEFAULT 'staff'
        CHECK (role IN ('superadmin', 'admin', 'staff')),

    -- Employee Profile
    employee_id VARCHAR(50) UNIQUE,
    profile_photo VARCHAR(255),

    -- Account Status
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_approved BOOLEAN NOT NULL DEFAULT FALSE,

    -- Approval Details
    approved_by BIGINT REFERENCES login_database(id)
        ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    rejection_reason TEXT,

    -- Login Security
    failed_login_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (failed_login_attempts >= 0),
    locked_until TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,

    -- Password and Record Timestamps
    password_changed_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Validation Rules
    CONSTRAINT chk_login_first_name
        CHECK (LENGTH(TRIM(first_name)) > 0),

    CONSTRAINT chk_login_last_name
        CHECK (LENGTH(TRIM(last_name)) > 0),

    CONSTRAINT chk_login_username
        CHECK (LENGTH(TRIM(username)) > 0),

    CONSTRAINT chk_login_email
        CHECK (LENGTH(TRIM(email)) > 0),

    CONSTRAINT chk_login_mobile
        CHECK (mobile ~ '^[0-9]{10}$')
);


-- 🟦 USER ACCOUNT INDEXES
-- Improve account filtering and lookup performance.

CREATE INDEX IF NOT EXISTS idx_login_database_role
    ON login_database(role);

CREATE INDEX IF NOT EXISTS idx_login_database_approval
    ON login_database(is_approved, is_active);

CREATE INDEX IF NOT EXISTS idx_login_database_created
    ON login_database(created_at DESC);


-- 🟪 2. LOGIN ACTIVITY LOG
-- Stores successful/failed login and account activities.

CREATE TABLE IF NOT EXISTS login_activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT REFERENCES login_database(id)
        ON DELETE SET NULL,

    username_entered VARCHAR(150),

    activity_type VARCHAR(30) NOT NULL
        CHECK (activity_type IN (
            'login_success',
            'login_failed',
            'logout',
            'approved',
            'rejected',
            'password_reset',
            'signup',
            'account_locked',
            'password_changed',
            'account_deactivated',
            'account_activated'
        )),

    -- Request Details
    ip_address INET,
    user_agent TEXT,

    -- Additional non-sensitive information
    details TEXT,

    created_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- Activity Log Indexes
CREATE INDEX IF NOT EXISTS idx_login_activity_user
    ON login_activity_log(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_login_activity_type
    ON login_activity_log(activity_type, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_login_activity_created
    ON login_activity_log(created_at DESC);


-- 🟪 3. PASSWORD RESET TOKENS
-- Stores hashed reset tokens and their expiration time.

CREATE TABLE IF NOT EXISTS login_password_reset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL REFERENCES login_database(id)
        ON DELETE CASCADE,

    token_hash VARCHAR(128) NOT NULL UNIQUE,

    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- Password Reset Index
CREATE INDEX IF NOT EXISTS idx_login_reset_user
    ON login_password_reset(user_id, expires_at);


-- 🟩 4. AUTOMATIC UPDATED_AT TIMESTAMP
-- Updates updated_at whenever a user account changes.

CREATE OR REPLACE FUNCTION update_login_database_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- Remove existing trigger before recreating it.
DROP TRIGGER IF EXISTS trg_login_database_updated_at
ON login_database;


-- Automatically update the timestamp on account changes.
CREATE TRIGGER trg_login_database_updated_at
BEFORE UPDATE ON login_database
FOR EACH ROW
EXECUTE FUNCTION update_login_database_timestamp();


-- 🟨 5. DATABASE VERIFICATION
-- Confirm that all three login tables exist.

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN (
      'login_database',
      'login_activity_log',
      'login_password_reset'
  )
ORDER BY table_name;


-- Count registered user accounts.
SELECT COUNT(*) AS total_users
FROM login_database;


